package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

// capabilityName is the form of x-capability: a name in lower case, with dots for its parts
// and hyphens in its words, and a number (#1748, docs/explanation/versions.md).
var capabilityName = regexp.MustCompile(`^[a-z][a-z0-9-]*(\.[a-z][a-z0-9-]*)*/[1-9][0-9]*$`)

// capabilities is every capability the documents name, sorted.
func capabilities(rpcs []*RPC) []string {
	seen := map[string]bool{}
	var all []string
	for _, rpc := range rpcs {
		for _, m := range rpc.Methods {
			if !seen[m.Capability] {
				seen[m.Capability] = true
				all = append(all, m.Capability)
			}
		}
	}
	sort.Strings(all)
	return all
}

// capabilityWord is a capability as one identifier, in camel case: agents.edit-queued/1 is
// agentsEditQueued1.
func capabilityWord(c string) string {
	var b strings.Builder
	for i, word := range strings.FieldsFunc(c, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		r := []rune(word)
		if i > 0 {
			r[0] = unicode.ToUpper(r[0])
		}
		b.WriteString(string(r))
	}
	return b.String()
}

// rpcName is the name of a document's method table: Host or Control.
func rpcName(rpc *RPC) string {
	return map[string]string{"host": "Host", "control": "Control"}[rpc.Target]
}

func rpcFile(rpc *RPC) string {
	return map[string]string{"host": "daemon", "control": "control"}[rpc.Target]
}

