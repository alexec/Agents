// tsCapabilities is Web/src/protocol/capabilities.generated.ts.
func tsCapabilities(rpcs []*RPC) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
//
// The capabilities that Packages/Wire names, x-capability on each method (#1748), and the
// capability of each method and notification. docs/explanation/versions.md says how they decide.

export const Capability = {
`)
	for _, c := range capabilities(rpcs) {
		fmt.Fprintf(&b, "  %s: %q,\n", capabilityWord(c), c)
	}
	b.WriteString("} as const;\n\nexport type Capability = (typeof Capability)[keyof typeof Capability];\n")
	for _, rpc := range rpcs {
		fmt.Fprintf(&b, "\n/** The capability of each method and notification in %s.openrpc.json. */\nexport const %sCapabilities: Readonly<Record<string, Capability>> = {\n",
			rpcFile(rpc), rpcName(rpc))
		for _, m := range rpc.Methods {
			fmt.Fprintf(&b, "  %q: %q,\n", m.Name, m.Capability)
		}
		b.WriteString("};\n")
	}
	return b.String()
}

// swiftCapabilities is AgentsKitCore's Capabilities.generated.swift, the one Swift file
// made from Packages/Wire.
func swiftCapabilities(rpcs []*RPC) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
// swiftlint:disable all

/// The capabilities that Packages/Wire names, x-capability on each method (#1748), and the
/// capability of each method and notification. docs/explanation/versions.md says how they decide.
public enum Capability {
`)
	for _, c := range capabilities(rpcs) {
		fmt.Fprintf(&b, "    public static let %s = %q\n", capabilityWord(c), c)
	}
	for _, rpc := range rpcs {
		fmt.Fprintf(&b, "\n    /// The capability of each method and notification in %s.openrpc.json.\n    public static let %s: [String: String] = [\n",
			rpcFile(rpc), rpc.Target)
		for _, m := range rpc.Methods {
			fmt.Fprintf(&b, "        %q: %q,\n", m.Name, m.Capability)
		}
		b.WriteString("    ]\n")
	}
	b.WriteString("}\n")
	return b.String()
}
