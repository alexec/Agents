// The meaning-types first, in this order, as generated.ts has always begun.
var prelude = []string{"JSONValue", "UUID", "Base64", "WireDate", "URLString"}

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// typescript makes Web/src/protocol/generated.ts: every definition, then the methods and
// notifications the web page uses (the `web` tag) from both OpenRPC documents.
func typescript(doc *Document, rpcs []*RPC) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
//
// Every type is a definition in Packages/Wire/daemon.schema.json; Methods, MethodTarget and
// Notifications are the methods tagged "web" in daemon.openrpc.json and control.openrpc.json.
// Change the schema, then run scripts/wire.sh gen (#1135).

`)
	done := map[string]bool{}
	for _, name := range prelude {
		if s, ok := doc.Definitions[name]; ok {
			b.WriteString(tsDefinition(name, s))
			done[name] = true
		}
	}
	for _, name := range doc.Names {
		if s := doc.Definitions[name]; s.TSType != "" && !done[name] {
			b.WriteString(tsDefinition(name, s))
			done[name] = true
		}
	}

	for _, rpc := range rpcs {
		if len(rpc.Errors) == 0 {
			continue
		}
		b.WriteString("\n/** DaemonAPI.Failure: the codes a call can fail with. */\nexport const Failure = {\n")
		for _, e := range rpc.Errors {
			fmt.Fprintf(&b, "  %s: %d,\n", e.Name, e.Code)
		}
		b.WriteString("} as const;\n")
	}

	for _, name := range doc.Names {
		if !done[name] {
			b.WriteString("\n" + tsDefinition(name, doc.Definitions[name]))
		}
	}

	type row struct {
		m      Method
		target string
	}
	var methods, notes []row
	for _, rpc := range rpcs {
		for _, m := range rpc.Methods {
			if !m.Web {
				continue
			}
			if m.Notification {
				notes = append(notes, row{m, rpc.Target})
			} else {
				methods = append(methods, row{m, rpc.Target})
			}
		}
	}
	sortRows := func(rows []row) {
		for i := 1; i < len(rows); i++ {
			for j := i; j > 0 && rows[j].m.Name < rows[j-1].m.Name; j-- {
				rows[j], rows[j-1] = rows[j-1], rows[j]
			}
		}
	}
	sortRows(methods)
	sortRows(notes)

	b.WriteString("\n/** Every method the web remote may call: its params and its result. */\nexport interface Methods {\n")
	for _, r := range methods {
		fmt.Fprintf(&b, "  %q: { params: %s; result: %s };\n", r.m.Name, tsType(r.m.Params), tsType(r.m.Result))
	}
	b.WriteString("}\n\n/** Whether a method goes to a host (with `h`) or to the control plane itself. */\nexport const MethodTarget = {\n")
	for _, r := range methods {
		fmt.Fprintf(&b, "  %q: %q,\n", r.m.Name, r.target)
	}
	b.WriteString("} as const;\n\n/** Every notification the web remote hears, and its params. */\nexport interface Notifications {\n")
	for _, r := range notes {
		fmt.Fprintf(&b, "  %q: %s;\n", r.m.Name, tsType(r.m.Params))
	}
	b.WriteString("}\n\n/** Each interface's keys, for checking Swift-encoded fixtures against these types. */\n" +
		"export const Shapes: Record<string, { required: readonly string[]; optional: readonly string[] }> = {\n")
	for _, name := range doc.Names {
		s := doc.Definitions[name]
		if !tsInterface(s) {
			continue
		}
		var required, optional []string
		for _, p := range s.Properties {
			if s.IsRequired(p.Name) {
				required = append(required, fmt.Sprintf("%q", p.Name))
			} else {
				optional = append(optional, fmt.Sprintf("%q", p.Name))
			}
		}
		fmt.Fprintf(&b, "  %s: { required: [%s], optional: [%s] },\n", tsKey(name),
			strings.Join(required, ", "), strings.Join(optional, ", "))
	}
	b.WriteString("};\n")
	return b.String()
}

// tsInterface says whether a definition is written as an interface: an object with named
// properties, or an object that allows none.
func tsInterface(s *Schema) bool {
	return s.TSType == "" && s.Is("object") && (len(s.Properties) > 0 || (s.NoMore && s.More == nil))
}

func tsDefinition(name string, s *Schema) string {
	var b strings.Builder
	b.WriteString(tsComment(s.Description, ""))
	switch {
	case s.TSType != "":
		fmt.Fprintf(&b, "export type %s = %s;\n", name, s.TSType)
	case tsInterface(s):
		if len(s.Properties) == 0 {
			fmt.Fprintf(&b, "export interface %s {}\n", name)
			break
		}
		fmt.Fprintf(&b, "export interface %s {\n", name)
		for _, p := range s.Properties {
			b.WriteString(tsComment(p.Schema.Description, "  "))
			optional := "?"
			if s.IsRequired(p.Name) {
				optional = ""
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", tsKey(p.Name), optional, tsType(p.Schema))
		}
		b.WriteString("}\n")
	default:
		_, _, cases := s.Cases()
		_, tagged := s.Tagged()
		if cases || tagged {
			fmt.Fprintf(&b, "export type %s =\n", name)
			for i, m := range s.AnyOf {
				end := ""
				if i == len(s.AnyOf)-1 {
					end = ";"
				}
				member := tsType(m)
				if tagged {
					member = tsMember(m)
				}
				fmt.Fprintf(&b, "  | %s%s\n", member, end)
			}
		} else if len(s.Enum) > 1 {
			// A value per line, so that two features that each add one do not touch the
			// same line (#2020).
			fmt.Fprintf(&b, "export type %s =\n", name)
			for i, v := range s.Enum {
				end := ""
				if i == len(s.Enum)-1 {
					end = ";"
				}
				fmt.Fprintf(&b, "  | %s%s\n", tsLiteral(v), end)
			}
		} else {
			fmt.Fprintf(&b, "export type %s = %s;\n", name, tsType(s))
		}
	}
	return b.String()
}

// tsMember is one member of a union on a line of its own: an object too long for the line
// gets a line per property.
func tsMember(s *Schema) string {
	one := tsType(s)
	if utf8.RuneCountInString("  | "+one) <= width || len(s.Properties) == 0 || s.TSType != "" {
		return one
	}
	var b strings.Builder
	b.WriteString("{\n")
	for _, p := range s.Properties {
		optional := "?"
		if s.IsRequired(p.Name) {
			optional = ""
		}
		fmt.Fprintf(&b, "      %s%s: %s;\n", tsKey(p.Name), optional, tsType(p.Schema))
	}
	b.WriteString("    }")
	return b.String()
}

// width is how long a comment line may be.
const width = 100

// tsComment writes a description as a doc comment, on one line when it fits.
func tsComment(text, indent string) string {
	if text == "" {
		return ""
	}
	if one := indent + "/** " + text + " */"; utf8.RuneCountInString(one) <= width && !strings.Contains(text, "\n") {
		return one + "\n"
	}
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, para := range strings.Split(text, "\n") {
		line := ""
		for _, word := range strings.Fields(para) {
			if line != "" && utf8.RuneCountInString(indent+" * "+line+" "+word) > width {
				b.WriteString(indent + " * " + line + "\n")
				line = ""
			}
			if line != "" {
				line += " "
			}
			line += word
		}
		b.WriteString(strings.TrimRight(indent+" * "+line, " ") + "\n")
	}
	b.WriteString(indent + " */\n")
	return b.String()
}

func tsKey(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	return fmt.Sprintf("%q", name)
}

func tsLiteral(v any) string {
	b, _ := json.Marshal(v)
	return string(b)
}

// tsType is the TypeScript for a schema written inline.
func tsType(s *Schema) string {
	switch {
	case s.TSType != "":
		return s.TSType
	case s.Ref != "":
		return s.RefName()
	case s.AnyOf != nil:
		parts := make([]string, len(s.AnyOf))
		for i, m := range s.AnyOf {
			parts[i] = tsType(m)
		}
		return strings.Join(parts, " | ")
	case s.HasConst:
		return tsLiteral(s.Const)
	case s.Enum != nil:
		parts := make([]string, len(s.Enum))
		for i, v := range s.Enum {
			parts[i] = tsLiteral(v)
		}
		return strings.Join(parts, " | ")
	case len(s.Types) > 1:
		parts := make([]string, len(s.Types))
		for i, t := range s.Types {
			parts[i] = tsType(&Schema{Types: []string{t}})
		}
		return strings.Join(parts, " | ")
	case s.Is("string"):
		return "string"
	case s.Is("number"), s.Is("integer"):
		return "number"
	case s.Is("boolean"):
		return "boolean"
	case s.Is("null"):
		return "null"
	case s.Is("array"):
		if s.Items == nil {
			return "JSONValue[]"
		}
		item := tsType(s.Items)
		if s.MinItems != nil && s.MaxItems != nil && *s.MinItems == *s.MaxItems && *s.MinItems > 0 {
			parts := make([]string, *s.MinItems)
			for i := range parts {
				parts[i] = item
			}
			return "[" + strings.Join(parts, ", ") + "]"
		}
		if strings.ContainsAny(item, "|&") && !strings.HasPrefix(item, "{") {
			item = "(" + item + ")"
		}
		return item + "[]"
	case s.Is("object"):
		if len(s.Properties) > 0 {
			parts := make([]string, len(s.Properties))
			for i, p := range s.Properties {
				optional := "?"
				if s.IsRequired(p.Name) {
					optional = ""
				}
				parts[i] = fmt.Sprintf("%s%s: %s", tsKey(p.Name), optional, tsType(p.Schema))
			}
			return "{ " + strings.Join(parts, "; ") + " }"
		}
		if s.More != nil && s.More.Not != nil {
			return "Record<string, never>"
		}
		if s.More != nil {
			return "Record<string, " + tsType(s.More) + ">"
		}
		return "{}"
	}
	return "JSONValue"
}
